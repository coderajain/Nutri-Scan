def seed_lm_rules(db: Session, admin_user: User = None) -> RuleVersion:
    """Creates initial RuleVersion LM-PC-2011-v1.0 with all 20 statutory rules."""
    version_tag = "LM-PC-2011-v1.0"
    existing_version = db.query(RuleVersion).filter(RuleVersion.version_tag == version_tag).first()

    if existing_version:
        logger.info(f"Rule version {version_tag} already exists with {len(existing_version.rules)} rules.")
        return existing_version

    admin_id = admin_user.id if admin_user else None

    rule_version = RuleVersion(
        version_tag=version_tag,
        title="Legal Metrology (Packaged Commodities) Rules 2011 & FSSAI 2020 (v1.0)",
        description="Comprehensive statutory ruleset covering mandatory declarations under LM-PC Rules 2011 and FSSAI Labelling Regulations 2020.",
        is_active=True,
        created_by_id=admin_id,
    )
    db.add(rule_version)
    db.flush()

    for item in LM_RULES_DATA:
        rule = Rule(
            rule_version_id=rule_version.id,
            rule_code=item["rule_code"],
            title=item["title"],
            field_name=item["field_name"],
            category=item["category"],
            description=item["description"],
            legal_reference=item["legal_reference"],
            severity=item["severity"],
            is_mandatory=item["is_mandatory"],
            validation_type=item["validation_type"],
            validation_params=item["validation_params"],
            is_active=True,
        )
        db.add(rule)

    db.commit()
    db.refresh(rule_version)
    logger.info(f"Seeded RuleVersion '{version_tag}' with {len(LM_RULES_DATA)} statutory rules.")
    return rule_version
